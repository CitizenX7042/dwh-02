  ID int identity(100,100), 
  S_ID INT,
  LineNoFS Int

)
Insert @Line_TableAll (S_ID,LineNoFS) Select ID,LineNoForSorting From StockMoves 
Where StockID=@StockID Order By StockMoves.LineNoForSorting,StockMoves.id

UPDATE  STOCKMOVES
SET STOCKMOVES.LineNoForSorting = (SELECT TT1.ID+100
from @Line_TableAll As TT1 WHERE TT1.S_ID=StockMoves.id And TT1.ID >0
AND StockMoves.StockId=@StockID)Where StockMoves.StockId=@StockID 

COMMIT TRAN



GO
